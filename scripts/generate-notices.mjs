import fs from 'node:fs'
import path from 'node:path'
const root = process.cwd()
const read = (p) => fs.readFileSync(p, 'utf8')
const pkg = JSON.parse(read('package.json'))
const visited = new Set()
const entries = []
function findPackage(name, from) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const p = path.join(dir, 'node_modules', name, 'package.json')
    if (fs.existsSync(p)) return fs.realpathSync(path.dirname(p))
    if (path.dirname(dir) === dir) return null
  }
}
function visit(name, from, optional = false) {
  const dir = findPackage(name, from)
  if (!dir) {
    if (optional) return
    throw Error(`Missing license package: ${name}`)
  }
  if (visited.has(dir)) return
  visited.add(dir)
  const meta = JSON.parse(read(path.join(dir, 'package.json')))
  const texts = []
  function collect(folder, depth) {
    for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue
      const p = path.join(folder, entry.name)
      if (entry.isFile() && /^(licen[sc]e|notice|copying|copyright)([.-]|$)/i.test(entry.name))
        texts.push(`${path.relative(dir, p)}\n${read(p)}`)
      else if (entry.isDirectory() && depth < 3) collect(p, depth + 1)
    }
  }
  collect(dir, 0)
  if (!texts.length && meta.repository?.startsWith?.('https://github.com/micromark/micromark/'))
    texts.push(read('docs/licenses/micromark-MIT.txt'))
  entries.push({
    name: `${meta.name}@${meta.version}`,
    license:
      typeof meta.license === 'string'
        ? meta.license
        : JSON.stringify(meta.license || meta.licenses || 'See source'),
    source:
      typeof meta.repository === 'string'
        ? meta.repository
        : meta.repository?.url || meta.homepage || '',
    text: texts.join('\n\n'),
  })
  for (const name of Object.keys(meta.dependencies || {}))
    visit(name, dir, Boolean(meta.optionalDependencies?.[name]))
  for (const name of Object.keys(meta.optionalDependencies || {})) visit(name, dir, true)
}
for (const name of Object.keys(pkg.dependencies)) visit(name, root)
const androidFile = 'docs/licenses/android-runtime.json'
entries.push(...JSON.parse(read(androidFile)))
entries.sort((a, b) => a.name.localeCompare(b.name))
const version = /versionName\s+"([^"]+)"/.exec(read('android/app/build.gradle'))?.[1] || pkg.version
fs.mkdirSync('src/generated', { recursive: true })
fs.writeFileSync(
  'src/generated/notices.ts',
  `// Generated by scripts/generate-notices.mjs; preserve upstream license text.\nexport const notices = ${JSON.stringify({ version, upstream: read('LICENSE'), entries }, null, 2)}\n`
)
console.log(`Generated ${entries.length} dependency notices`)
